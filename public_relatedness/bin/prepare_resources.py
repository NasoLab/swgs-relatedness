#!/usr/bin/env python3
"""Explicit public-upstream acquisition and SHA256 verification; never regenerate or bundle payloads."""
import argparse
import gzip
import hashlib
import importlib.util
import json
import os
import tempfile
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location('asset_paths', ROOT / 'bin/assets.py')
assets = importlib.util.module_from_spec(spec)
spec.loader.exec_module(assets)


def sha256(path):
    h = hashlib.sha256()
    with Path(path).open('rb') as stream:
        for data in iter(lambda: stream.read(1024 * 1024), b''): h.update(data)
    return h.hexdigest()


def fetch(record, directory, opener=urllib.request.urlopen):
    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True)
    dest = directory / record['filename']
    if dest.exists():
        if sha256(dest) != record['sha256']: raise ValueError('Existing file differs from frozen identity: ' + dest.name)
        return dest
    fd, name = tempfile.mkstemp(prefix='.swgs-acquire-', dir=directory)
    try:
        with os.fdopen(fd, 'wb') as out:
            with opener(record['url'], timeout=60) as response:
                stream = gzip.GzipFile(fileobj=response) if record.get('gzip') else response
                for data in iter(lambda: stream.read(1024 * 1024), b''): out.write(data)
        if sha256(name) != record['sha256']: raise ValueError('Downloaded content checksum mismatch: ' + dest.name)
        # Hard-link fails atomically if another writer created the destination.
        os.link(name, dest)
        return dest
    finally:
        Path(name).unlink(missing_ok=True)


def records():
    refs = {r['id']: r for r in assets.REFERENCES}
    fasta = refs['hg38_fasta']; pfreq = refs['llr_pfreq']; helper = assets.SOURCES['helper']
    return {'hg38': dict(filename=fasta['filename'], sha256=fasta['sha256'], url=fasta['source_url'], gzip=True),
            'pfreq': dict(filename=pfreq['filename'], sha256=pfreq['sha256'], url='https://raw.githubusercontent.com/tgac-vumc/CNA_clonality/bbffb4a15a425ce032537cf95b2d68dbc1d87f15/reference/pfreq_lusc_tcga_split.csv'),
            'llr-helper': dict(filename=helper['filename'], sha256=helper['sha256'], url=helper['url'])}


def verify(directory):
    checks = []
    for r in assets.REFERENCES + [dict(assets.SOURCES['helper'], id='llr_helper')]:
        path = Path(directory) / r['filename']
        if not path.is_file(): raise ValueError('Missing ' + r['filename'] + assets.missing_hint(r.get('config_param', r['id'])))
        if sha256(path) != r['sha256']: raise ValueError('Checksum mismatch: ' + r['filename'])
        checks.append(r.get('id', r['filename']))
    return checks


def main():
    p = argparse.ArgumentParser(description=__doc__, epilog='Fetching is opt-in from the original public upstream, not a redistribution grant. Confirm lawful use under upstream terms. PE150 and indexes are never downloaded or regenerated by this command.')
    p.add_argument('--resources', type=Path, required=True)
    p.add_argument('--fetch', action='append', choices=['hg38', 'pfreq', 'llr-helper'], default=[])
    p.add_argument('--verify', action='store_true')
    a = p.parse_args()
    try:
        sources = records()
        downloaded = [fetch(sources[key], a.resources).name for key in a.fetch]
        checked = verify(a.resources) if a.verify else []
        print(json.dumps(dict(fetched=downloaded, fetched_sha256_verified=downloaded, full_resource_set_verified=checked, references_regenerated=False), indent=2))
    except (OSError, ValueError) as e: p.exit(2, 'Resource setup failed: ' + str(e) + '\n')


if __name__ == '__main__': main()
